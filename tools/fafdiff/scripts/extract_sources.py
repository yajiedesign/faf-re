#!/usr/bin/env python3
"""Copy engine source ranges into the fafdiff build directory.

fafdiff compiles the engine's own translation units, with the engine's own
switches. A few functions, however, live in a TU the harness cannot link as a
whole: src/moho/sim/Sim.cpp has a non-COMDAT .CRT$XCU static initializer,
which is a link root that references every static object in the file, so
linking that TU drags in most of the engine (591 of 941 TUs).

Those functions are declared in tools/fafdiff/extract.json as explicit line
ranges, and this script copies the ranges into the build directory. The copy
is a build output: tools/fafdiff/CMakeLists.txt compiles it like any other
engine translation unit.

The script does three things and nothing else:

  1. checks the source file's sha256 against the one in the config;
  2. slices the configured line ranges (plain array indexing - no symbol
     search, no C++ parsing, the ranges are written by hand);
  3. checks the generated file's sha256 against the one in the config.

Both hashes are the guard against silent drift:

  * a source edit invalidates "sourceSha256", so the ranges - written for the
    old revision - are not trusted, and the agent has to re-check them;
  * "outputSha256" pins the exact bytes of the generated file that a human or
    an agent read and approved. It starts empty: the first run generates the
    file, prints its sha256 and fails, so the run cannot pass without someone
    looking at what was actually extracted.

Errors are collected and reported together, at most MAX_ERRORS of them; when
that many have accumulated the remaining entries are not processed. A run
with any error exits non-zero, and the build stops.

Usage:
    extract_sources.py --config extract.json --root <repo> --outdir <build>/generated
    extract_sources.py --config extract.json --root <repo> --deps      # source paths
    extract_sources.py --config extract.json --root <repo> --outputs   # output paths
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

MAX_ERRORS = 10


class Reporter:
  def __init__(self, config_path: str) -> None:
    self.config_path = config_path
    self.messages: list[str] = []

  def error(self, where: str, what: str, fix: str) -> None:
    self.messages.append(f"{where}\n    {what}\n    -> {fix}")

  def full(self) -> bool:
    return len(self.messages) >= MAX_ERRORS

  def report(self) -> int:
    if not self.messages:
      return 0
    out = [f"fafdiff extract: {len(self.messages)} error(s) in {self.config_path}", ""]
    for number, message in enumerate(self.messages, 1):
      out.append(f"{number}. {message}")
      out.append("")
    sys.stderr.write("\n".join(out) + "\n")
    return 1


def sha256_of_bytes(data: bytes) -> str:
  return hashlib.sha256(data).hexdigest()


def sha256_of_file(path: str) -> str:
  digest = hashlib.sha256()
  with open(path, "rb") as handle:
    for chunk in iter(lambda: handle.read(1 << 20), b""):
      digest.update(chunk)
  return digest.hexdigest()


def load_config(path: str) -> dict:
  with open(path, "r", encoding="utf-8") as handle:
    config = json.load(handle)
  files = config.get("files")
  if not isinstance(files, list) or not files:
    raise ValueError(f"{path} has no \"files\" list")
  return config


def source_path(entry: dict, root: str) -> str:
  return os.path.normpath(os.path.join(root, entry["source"]))


def output_path(entry: dict, outdir: str) -> str:
  return os.path.normpath(os.path.join(outdir, entry["output"]))


def render(entry: dict, lines: list[str], ranges: list[tuple[int, int]]) -> str:
  banner = [
    "// GENERATED by tools/fafdiff/scripts/extract_sources.py - do not edit.",
    f"// Source: {entry['source']} lines "
    + ", ".join(f"{first}-{last}" for (first, last) in ranges),
    "// Compiled with the engine's own switches, so the function behaves here",
    "// exactly as it does in the engine.",
    "",
  ]
  includes = [f'#include "{header}"' for header in entry.get("includes", [])]
  parts = banner + includes
  if includes:
    parts.append("")
  body = "\n".join(line for (first, last) in ranges for line in lines[first - 1:last])
  return "\n".join(parts) + "\n" + body + "\n"


def parse_ranges(entry: dict, line_count: int, reporter: Reporter, where: str) -> list[tuple[int, int]] | None:
  ranges: list[tuple[int, int]] = []
  for item in entry.get("ranges", []):
    if not isinstance(item, list) or len(item) != 2:
      reporter.error(where, f"a range must be [first, last], got {item!r}",
                     "fix \"ranges\" in the config")
      return None
    first, last = int(item[0]), int(item[1])
    if first < 1 or last < first or last > line_count:
      reporter.error(where, f"range [{first}, {last}] is outside 1..{line_count}",
                     "fix \"ranges\" in the config")
      return None
    ranges.append((first, last))
  if not ranges:
    reporter.error(where, "no \"ranges\"", "list the line ranges to copy")
    return None
  ranges.sort()
  for (first, last), (next_first, _) in zip(ranges, ranges[1:]):
    if next_first <= last:
      reporter.error(where, f"ranges overlap at line {next_first}",
                     "make the ranges disjoint")
      return None
  return ranges


def process(entry: dict, root: str, outdir: str, reporter: Reporter) -> None:
  where = f"{entry['source']} -> {entry['output']}"

  source = source_path(entry, root)
  if not os.path.isfile(source):
    reporter.error(where, f"{entry['source']} does not exist", "fix \"source\"")
    return

  expected_source = entry.get("sourceSha256", "")
  actual_source = sha256_of_file(source)
  if not expected_source:
    reporter.error(
      where,
      f"\"sourceSha256\" is empty (the file is {actual_source})",
      "put that hash in \"sourceSha256\" once the ranges are right, then re-run")
    return
  if actual_source != expected_source:
    reporter.error(
      where,
      f"{entry['source']} changed since its ranges were written\n"
      f"      expected {expected_source}\n"
      f"      actual   {actual_source}",
      "re-read the function, update \"ranges\" and \"sourceSha256\" in the config")
    return

  with open(source, "r", encoding="utf-8", newline="") as handle:
    lines = handle.read().splitlines()
  ranges = parse_ranges(entry, len(lines), reporter, where)
  if ranges is None:
    return

  text = render(entry, lines, ranges)
  target = output_path(entry, outdir)
  os.makedirs(os.path.dirname(target), exist_ok=True)
  previous = None
  if os.path.isfile(target):
    with open(target, "r", encoding="utf-8", newline="") as handle:
      previous = handle.read()
  if previous != text:
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
      handle.write(text)

  actual_output = sha256_of_bytes(text.encode("utf-8"))
  expected_output = entry.get("outputSha256", "")
  if not expected_output:
    reporter.error(
      where,
      f"generated {os.path.relpath(target, root).replace(os.sep, '/')}\n"
      f"      sha256 {actual_output}\n"
      f"      but \"outputSha256\" is empty, so nobody has approved these bytes",
      "open the generated file, check that the ranges bracket exactly the intended "
      f"function, then set \"outputSha256\" to {actual_output}")
    return
  if actual_output != expected_output:
    reporter.error(
      where,
      f"the generated file changed\n"
      f"      expected {expected_output}\n"
      f"      actual   {actual_output}",
      "open the generated file, check the new extraction, then update "
      "\"outputSha256\" to the actual value")


def main() -> int:
  parser = argparse.ArgumentParser(description="extract engine source ranges for fafdiff")
  parser.add_argument("--config", required=True)
  parser.add_argument("--root", required=True, help="repository root")
  parser.add_argument("--outdir", help="where the generated .cpp files go")
  mode = parser.add_mutually_exclusive_group()
  mode.add_argument("--deps", action="store_true", help="print the source files, do nothing else")
  mode.add_argument("--outputs", action="store_true", help="print the generated files, do nothing else")
  args = parser.parse_args()

  root = os.path.abspath(args.root)
  try:
    config = load_config(args.config)
  except (OSError, ValueError, json.JSONDecodeError) as error:
    sys.stderr.write(f"fafdiff extract: {error}\n")
    return 1

  if args.deps:
    for entry in config["files"]:
      print(source_path(entry, root).replace(os.sep, "/"))
    return 0
  if args.outputs:
    if not args.outdir:
      sys.stderr.write("fafdiff extract: --outdir is required with --outputs\n")
      return 1
    for entry in config["files"]:
      print(output_path(entry, os.path.abspath(args.outdir)).replace(os.sep, "/"))
    return 0

  if not args.outdir:
    sys.stderr.write("fafdiff extract: --outdir is required\n")
    return 1

  outdir = os.path.abspath(args.outdir)
  reporter = Reporter(args.config)
  for entry in config["files"]:
    if reporter.full():
      break
    process(entry, root, outdir, reporter)

  return reporter.report()


if __name__ == "__main__":
  raise SystemExit(main())
